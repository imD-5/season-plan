"""Ports: what the application needs from the outside world.

Adapters implement these. The application never imports an adapter.
"""

from collections.abc import Callable, Sequence
from dataclasses import dataclass
from datetime import date
from typing import Protocol, Self

from season.domain.model import Category, CategoryAssignment, Event, Problem, ProblemQueue, SessionMark, Task, Week


# ── persistence ────────────────────────────────────────────────────────────
class TaskRepository(Protocol):
    def get(self, task_id: int) -> Task: ...
    def add(self, task: Task) -> Task: ...
    def remove(self, task_id: int) -> None: ...
    def assign(self, task_id: int, assignment: CategoryAssignment) -> None: ...
    def set_mark(self, task_id: int, slot: int, mark: SessionMark) -> None: ...
    def set_note(self, task_id: int, slot: int, note: str | None) -> None: ...
    def clear_mark(self, task_id: int, slot: int) -> None: ...
    def next_position(self, week_start: date) -> int: ...
    def automatic_in(self, category: str) -> list[Task]: ...
    def upsert_planned(self, task: Task) -> None: ...
    def remove_planned_except(self, week_start: date, keep_keys: Sequence[str]) -> None: ...


class WeekRepository(Protocol):
    def all(self) -> list[Week]: ...
    def exists(self, start: date) -> bool: ...
    def upsert(self, week: Week) -> None: ...


class CategoryRepository(Protocol):
    def all(self) -> list[Category]: ...
    def exists(self, key: str) -> bool: ...
    def add(self, category: Category) -> None: ...
    def upsert_builtin(self, category: Category, position: int) -> None: ...


class EventRepository(Protocol):
    def all(self) -> list[Event]: ...
    def replace_all(self, events: Sequence[Event]) -> None: ...


class ProblemRepository(Protocol):
    def queue(self) -> ProblemQueue: ...
    def save_position(self, position: int) -> None: ...
    def replace_list(self, problems: Sequence[Problem]) -> None: ...


class SettingsRepository(Protocol):
    def pages(self) -> int | None: ...
    def set_pages(self, pages: int | None) -> None: ...


class UnitOfWork(Protocol):
    """One transaction. Commits on clean exit, rolls back on exception."""

    tasks: TaskRepository
    weeks: WeekRepository
    categories: CategoryRepository
    events: EventRepository
    problems: ProblemRepository
    settings: SettingsRepository

    def __enter__(self) -> Self: ...
    def __exit__(self, *exc: object) -> None: ...


UnitOfWorkFactory = Callable[[], UnitOfWork]


# ── classification ─────────────────────────────────────────────────────────
@dataclass(frozen=True, slots=True)
class Prediction:
    category: str
    probability: float   # probability of the chosen category
    confidence: float    # how concentrated the whole distribution is


class ClassifierUnavailable(Exception):
    """No key, network down, API error. The caller falls back to OTHER."""


class Classifier(Protocol):
    def predict(self, text: str, categories: Sequence[Category]) -> Prediction: ...


# ── time and notifications ─────────────────────────────────────────────────
class Clock(Protocol):
    def today(self) -> date: ...


class Notifier(Protocol):
    def notify(self, title: str, body: str) -> None: ...
